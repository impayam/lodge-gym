// The M14 import report (SPEC-v11 A2): counts per source, per muscle and per region; duplicates; every record not
// imported with its reason; the hand-written list. Written to seed/library/m14/IMPORT-REPORT.md by
// `npm run library:report`. Pure: no I/O.

import { countsVolume } from "./category";
import type { DuplicateImage, LibraryRow } from "./library";
import { regionChecks, type DecisionFile, type DedupeEntry, type ScreeningFile } from "./libraryDecisions";
import { SOURCES, SOURCE_ORDER, type ScreenKind } from "./librarySources";
import { CANONICAL_MUSCLES } from "./muscles";
import { REGIONS, REGION_INFO, type RegionTag } from "./regions";

interface ReportInput {
  screening: ScreeningFile;
  files: DecisionFile[];
  dedupe: DedupeEntry[];
  /** The library without the M14 sources: seeded, free-exercise-db and hand-written rows. */
  before: { id: string; name_en: string; muscle_primary: string; category: string | null; source: string; muscles_secondary: string[] }[];
  added: LibraryRow[];
  tags: ReadonlyMap<string, RegionTag[]>;
  /** Exercises whose two images are the same picture: the second is left out (seed/library/duplicate-images.json). */
  duplicates: DuplicateImage[];
}

const SCREEN_LABEL: Record<Exclude<ScreenKind, "candidate" | "duplicate">, string> = {
  category: "category not imported (plyometrics, strongman)",
  equipment: "excluded equipment (kettlebell, band, ball, foam roller, TRX)",
  language: "name not in English",
  no_muscle: "no muscle in the source (strength)",
  no_equipment: "no equipment in the source",
};

export function m14ReportMarkdown(r: ReportInput): string {
  const lines: string[] = [];
  const list = <T>(title: string, items: T[], fmt: (x: T) => string, level = "##") => {
    lines.push(`${level} ${title} (${items.length})`, "");
    if (!items.length) lines.push("None.");
    for (const x of items) lines.push(`- ${fmt(x)}`);
    lines.push("");
  };
  const same = new Map(r.dedupe.filter((e) => e.decision === "same").map((e) => [e.candidate, e]));
  const addedBySource = new Map<string, number>();
  for (const a of r.added) addedBySource.set(a.source, (addedBySource.get(a.source) ?? 0) + 1);

  lines.push(
    "# Exercise library import report: M14 sources",
    "",
    "Generated by `npm run library:report` (SPEC-v11 M14 Phase A, sources and process approved by Payam on 2026-10-16).",
    "Names and facts are taken from every source; descriptions, instructions and media only where the licence allows",
    "(instructions are our own). Existing exercise ids never change; a duplicate is not added, nothing is merged.",
    "",
    "## Per source",
    "",
    "| Source | Commit | Licence | Records | Not imported automatically | Exact duplicates | Reviewed: added | Reviewed: excluded | Reviewed: duplicates |",
    "|---|---|---|---|---|---|---|---|---|"
  );
  for (const s of SOURCE_ORDER) {
    const recs = r.screening.records[s] ?? [];
    const auto = recs.filter((x) => x.kind !== "candidate" && x.kind !== "duplicate").length;
    const dup = recs.filter((x) => x.kind === "duplicate").length;
    const f = r.files.find((x) => x.source === s);
    const ds = f?.decisions ?? [];
    const dupReviewed = ds.filter((d) => same.has(`${s}:${d.sid}`)).length;
    const excluded = ds.filter((d) => d.decision === "exclude" && !same.has(`${s}:${d.sid}`)).length;
    lines.push(`| ${SOURCES[s].label} | \`${SOURCES[s].sha.slice(0, 7)}\` | ${SOURCES[s].licence} | ${recs.length} | ${auto} | ${dup} | ${addedBySource.get(s) ?? 0} | ${excluded} | ${dupReviewed} |`);
  }
  lines.push("", `Rows added from the M14 sources: **${r.added.length}**. Library after the import: **${r.before.length + r.added.length}** exercises (${r.before.length} before).`, "");

  // Categories.
  const perCat = new Map<string, number>();
  for (const a of r.added) perCat.set(a.category, (perCat.get(a.category) ?? 0) + 1);
  lines.push("## Rows added per category", "", "| Category | Counts toward volume | Rows |", "|---|---|---|", ...[...perCat].sort((a, b) => b[1] - a[1]).map(([c, n]) => `| ${c} | ${countsVolume(c) ? "yes" : "no (no region tags)"} | ${n} |`), "");

  // Muscles.
  const count = (rows: { muscle_primary: string }[], m: string) => rows.filter((x) => x.muscle_primary === m).length;
  const old = r.before.filter((x) => x.source !== "manual");
  const manual = r.before.filter((x) => x.source === "manual");
  lines.push("## Per muscle (main muscle)", "", "| Muscle | Seeded and free-exercise-db | Hand-written | M14 sources | Total |", "|---|---|---|---|---|");
  for (const m of CANONICAL_MUSCLES) lines.push(`| ${m} | ${count(old, m)} | ${count(manual, m)} | ${count(r.added, m)} | ${count(old, m) + count(manual, m) + count(r.added, m)} |`);
  lines.push("");

  // Regions.
  const all = [...r.before, ...r.added];
  const checks = regionChecks(all, r.tags);
  lines.push(
    "## Per region (exercises that count toward volume)",
    "",
    "Tagged by the reviewed rule table (worker/lib/regions.ts); stretching and cardio carry no region.",
    "",
    "| Region | Label | Primary | Any emphasis |",
    "|---|---|---|---|",
    ...REGIONS.map((g) => `| ${g} | ${REGION_INFO[g].label} | ${checks.primary.get(g)} | ${checks.anyTag.get(g)} |`),
    ""
  );
  const evidence = new Map<string, number>();
  for (const t of r.tags.values()) for (const x of t) evidence.set(`${x.emphasis} ${x.evidence}`, (evidence.get(`${x.emphasis} ${x.evidence}`) ?? 0) + 1);
  lines.push("| Emphasis and evidence | Tags |", "|---|---|", ...[...evidence].sort().map(([k, n]) => `| ${k} | ${n} |`), "");
  list("No region although counted (must be empty)", checks.untagged, (x) => `${x.name_en} (${x.muscle})`, "###");
  list("Two primary regions of one muscle outside the reviewed rules (must be empty)", checks.doublePrimary, (x) => x, "###");

  // Images.
  const withImages = r.added.filter((a) => a.media.length);
  lines.push(
    "## Images",
    "",
    "Only from open-licence sources, each image's own licence and author stored with it; AI-generated wger images are left out.",
    "",
    "| Source | Rows with images | Images |",
    "|---|---|---|",
    ...SOURCE_ORDER.map((s) => `| ${SOURCES[s].label} | ${withImages.filter((a) => a.source === s).length} | ${withImages.filter((a) => a.source === s).reduce((n, a) => n + a.media.length, 0)} |`),
    ""
  );
  list(
    "Same picture twice: one image kept (every source, seed/library/duplicate-images.json)",
    r.duplicates,
    (d) => `${d.name} (\`${d.id}\`): kept \`${d.keep.split("/").slice(-2).join("/")}\`, left out \`${d.drop.split("/").slice(-2).join("/")}\` (${d.reason})`,
    "###"
  );

  // Duplicates.
  lines.push("## Duplicates", "");
  for (const s of SOURCE_ORDER) {
    list(`${SOURCES[s].label}: exact duplicates (same words and equipment)`, (r.screening.records[s] ?? []).filter((x) => x.kind === "duplicate"), (x) => `${x.name} = ${x.match!.name} (\`${x.match!.id}\`)`, "###");
  }
  list("Reviewed duplicates (dedupe-review.json: same)", r.dedupe.filter((e) => e.decision === "same"), (e) => `${e.name} (\`${e.candidate}\`) = \`${e.duplicate_of}\`: ${e.reason}`, "###");
  list("Reviewed as different and added or decided on their own (dedupe-review.json: different)", r.dedupe.filter((e) => e.decision === "different"), (e) => `${e.name} (\`${e.candidate}\`) ≠ ${e.closest ? `${e.closest.name} (\`${e.closest.id}\`)` : "—"}: ${e.reason}`, "###");

  // Not imported.
  lines.push("## Not imported, with reasons", "");
  for (const s of SOURCE_ORDER) {
    for (const k of Object.keys(SCREEN_LABEL) as (keyof typeof SCREEN_LABEL)[]) {
      const xs = (r.screening.records[s] ?? []).filter((x) => x.kind === k);
      if (xs.length) list(`${SOURCES[s].label}: ${SCREEN_LABEL[k]}`, xs, (x) => `${x.name}${x.detail ? ` (${x.detail})` : ""}`, "###");
    }
    const f = r.files.find((x) => x.source === s);
    const ex = (f?.decisions ?? []).filter((d) => d.decision === "exclude" && !same.has(`${s}:${d.sid}`));
    if (ex.length) list(`${SOURCES[s].label}: excluded on review`, ex, (d) => `${d.name}: ${d.reason}`, "###");
  }

  list("Hand-written exercises (source 'manual', our own instructions, no media)", manual, (m) => `\`${m.id}\` ${m.name_en} (${m.muscle_primary})`);
  return lines.join("\n");
}
