// Builds seed/seed.sql from seed/program.json (SPEC §6). Runs on every deploy, so it is insert-only: it adds the seed
// rows a database is missing and never changes an existing row. The active program, approvals, archives and
// activations belong to the app (SPEC-v2 M8), and a deploy must never switch the program back (Payam, 2026-10-12).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const data = JSON.parse(readFileSync(here("./program.json"), "utf8"));
const CREATED = "2026-09-27T00:00:00.000Z";
// Program metadata for a fresh database, the same values migration 0006 backfills on an existing one.
const META = {
  fullbody4: { style: "seed_full_body", days_per_week: 4, approved_at: CREATED, archived_at: null },
  upperlower: { style: "seed_upper_lower", days_per_week: 4, approved_at: null, archived_at: CREATED },
};

const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const out = ["-- Generated by seed/generate.mjs from seed/program.json. Do not edit by hand. Insert-only: existing rows are never changed."];

for (const [k, v] of Object.entries(data.settings)) {
  out.push(`INSERT OR IGNORE INTO settings (key, value) VALUES (${q(k)}, ${q(v)});`);
}
for (const e of data.exercises) {
  out.push(
    `INSERT OR IGNORE INTO exercises (id, name_fa, name_en, muscle_primary, is_lower, equipment, cue_fa, cue_en, source, source_id, category) VALUES (${[e.id, e.name_fa, e.name_en, e.muscle_primary, e.is_lower, e.equipment, e.cue_fa, e.cue_en || null, "seed", e.id, "strength"].map(q).join(", ")});`
  );
}
for (const p of data.programs) {
  const m = META[p.id];
  if (!m) throw new Error(`seed program ${p.id} has no metadata in seed/generate.mjs`);
  out.push(
    `INSERT OR IGNORE INTO programs (id, name, active, created_at, style, days_per_week, generated_by, approved_at, archived_at) VALUES (${[p.id, p.name, p.active, CREATED, m.style, m.days_per_week, "seed", m.approved_at, m.archived_at].map(q).join(", ")});`
  );
  if (p.active) {
    out.push(
      `INSERT OR IGNORE INTO program_activations (id, program_id, started_at) SELECT ${q(`act-${p.id}-seed`)}, ${q(p.id)}, ${q(CREATED)} WHERE NOT EXISTS (SELECT 1 FROM program_activations WHERE program_id = ${q(p.id)});`
    );
  }
  p.days.forEach((d, di) => {
    out.push(
      `INSERT OR IGNORE INTO program_days (id, program_id, position, name_fa, name_en, focus_fa, est_minutes) VALUES (${[d.id, p.id, di + 1, d.name_fa, d.name_en, d.focus_fa, d.est_minutes].map(q).join(", ")});`
    );
    d.ex.forEach((x, xi) => {
      const row = [`${d.id}_${xi + 1}`, d.id, x.x, xi + 1, x.sets, x.reps[0], x.reps[1], x.per_leg ?? 0, x.time ?? 0, x.rest, x.tag ?? null, x.main ?? 0];
      out.push(`INSERT OR IGNORE INTO day_exercises (id, day_id, exercise_id, position, sets, reps_min, reps_max, per_leg, is_time, rest_sec, superset_tag, is_main) VALUES (${row.map(q).join(", ")});`);
    });
  });
}

const sql = out.join("\n") + "\n";
if (process.argv.includes("--check")) {
  const current = readFileSync(here("./seed.sql"), "utf8");
  if (current !== sql) {
    console.error("seed/seed.sql is out of date; run `npm run seed:build`.");
    process.exit(1);
  }
} else {
  writeFileSync(here("./seed.sql"), sql);
  console.log(`seed/seed.sql: ${out.length - 1} statements`);
}
